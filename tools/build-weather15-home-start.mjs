// Only normalize the initial tab state of the owner's private device export.
import assert from 'node:assert/strict';
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {resolve, relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import {randomBytes, createCipheriv, createDecipheriv, createHash} from 'node:crypto';
import {gzipSync, gunzipSync} from 'node:zlib';
import {widgetLayers} from './weather15-location-split.js';
import {formatJSONLines} from './json-copy-lines.js';

const [input, output] = process.argv.slice(2);
assert(input && output, 'Supply the private device export and private output directory');
const root = fileURLToPath(new URL('../', import.meta.url));
const privateDir = resolve(output);
assert(relative(root, privateDir).startsWith('../'), 'Keep private exports outside the repository');
const sourceBytes = readFileSync(input);
const before = JSON.parse(sourceBytes);
assert.equal(before['3'], 'Widgy Weather 15 - Recovery');
const layers = [...widgetLayers(before)];
assert.equal(layers.length, 1204);
assert.equal(new Set(layers.map(n => n.d0)).size, layers.length);
assert.equal(before['36'].length, 74);
const homeActions = layers.filter(n => n.z === '11' && n.s === 'HOME Tap');
assert.equal(homeActions.length, 4);
for (const n of homeActions) assert.equal(n['1a'], 'button_245,83010-247,246,195');
const widget = structuredClone(before);
assert.deepEqual(widget['1'].map(n => n.d0), [83010,245,247,246,195]);
assert.equal(widget['1'].find(n => n.d0 === 247).a, false);
for (const id of [83010,245,246,195]) assert.equal(widget['1'].find(n => n.d0 === id).a, undefined);
for (const id of [246,195]) widget['1'].find(n => n.d0 === id).a = false;
widget['3'] = 'Widgy Weather 15 - Home Start';
assert.deepEqual(widget['1'].filter(n => n.a !== false).map(n => n.d0), [83010,245]);
const restored = structuredClone(widget);
for (const id of [246,195]) delete restored['1'].find(n => n.d0 === id).a;
restored['3'] = before['3'];
assert.deepEqual(restored, before, 'Only two visibility flags and the identifying name may change');
const raw = Buffer.from(JSON.stringify(widget));
assert.deepEqual(JSON.parse(formatJSONLines(raw.toString())), widget);
const key = randomBytes(32), iv = randomBytes(12);
const aad = Buffer.from('widgy-weather15-home-start:v1:20261014');
const cipher = createCipheriv('aes-256-gcm', key, iv); cipher.setAAD(aad);
const ciphertext = Buffer.concat([cipher.update(gzipSync(raw)), cipher.final(), cipher.getAuthTag()]);
const envelope = {v:1, iv:iv.toString('base64url'), data:ciphertext.toString('base64url'), bytes:raw.length, sha256:createHash('sha256').update(raw).digest('hex')};
const decipher = createDecipheriv('aes-256-gcm', key, iv); decipher.setAAD(aad); decipher.setAuthTag(ciphertext.subarray(-16));
assert(gunzipSync(Buffer.concat([decipher.update(ciphertext.subarray(0,-16)), decipher.final()])).equals(raw));
mkdirSync(privateDir, {recursive:true, mode:0o700});
writeFileSync(resolve(privateDir, 'Widgy_Weather_15_Home_Start.json'), raw, {mode:0o600});
writeFileSync(resolve(privateDir, 'copy-key.txt'), key.toString('base64url'), {mode:0o600});
const origin = 'https://widgy-maps-world-glass-git-f50-widget-test-blue-sky12.vercel.app';
writeFileSync(resolve(privateDir, 'copy-url.txt'), origin+'/tools/widgy-weather15-home-start-copy.html#key='+key.toString('base64url'), {mode:0o600});
writeFileSync(new URL('./widgy-weather15-home-start.enc.json', import.meta.url), JSON.stringify(envelope)+'\n');
const report = {sourceSha256:createHash('sha256').update(sourceBytes).digest('hex'), layers:layers.length, variables:74, changes:['WEATHER initial visibility: hidden', 'HEALTH initial visibility: hidden', 'Identifying name: Home Start'], allOtherFieldsIdentical:true, matchesExistingHomeNavigation:true, encryptionRoundTrip:true, bytes:raw.length, sha256:envelope.sha256, nativeLoadVerified:false};
writeFileSync(resolve(privateDir, 'verification.json'), JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
