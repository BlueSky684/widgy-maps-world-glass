// Full private Weather 15 copies. Publish only encrypted envelopes.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {isDeepStrictEqual} from 'node:util';
import {createHash,randomBytes,createCipheriv,createDecipheriv} from 'node:crypto';
import {gzipSync,gunzipSync} from 'node:zlib';
const origin='https://widgy-maps-world-glass-git-f50-widget-test-blue-sky12.vercel.app';
const imagePath='assets/diagnostics/map-host-ab-15/snapshot.png';
const revision=process.argv[2];
assert(/^[a-f0-9]{40}$/.test(revision||''));
const raw=fs.readFileSync('work/private/Widgy_Health_Premium_1.json');
assert.equal(createHash('sha256').update(raw).digest('hex'),'433b9715ea3081e6cc11dc179ba790a0e62f685ca4e925ae81cf2e5f2a43a892');
const original=JSON.parse(raw);
assert.equal(original['3'],'Widgy Weather 15');
const keyPath='work/private/map-host-ab-15-key.json';
if(!fs.existsSync(keyPath))fs.writeFileSync(keyPath,JSON.stringify({key:randomBytes(32).toString('base64url')}),{mode:0o600});
const key=Buffer.from(JSON.parse(fs.readFileSync(keyPath)).key,'base64url');
const walk=nodes=>nodes.flatMap(n=>[n,...(n.z==='13'?walk(n['1']):[])]);
const getMap=w=>walk(w['1']).find(n=>n.d0===6170);
assert.equal(getMap(original)['1'],'Web URL');
assert.equal(getMap(original)['2'],'${widgy.map_request}');
const variable=w=>w['36'].find(v=>v['1']==='map_request');
assert.equal(variable(original)['3']['66'][0]['5'],'Custom Text');
const originals=fs.readFileSync('tools/widgy-health-premium-1.enc.json');
const output=[];
for(const name of ['A','B']){
 const widget=structuredClone(original);
 const url=name==='A'?`${origin}/${imagePath}`:`https://cdn.jsdelivr.net/gh/BlueSky684/widgy-maps-world-glass@${revision}/${imagePath}`;
 variable(widget)['3']['66'][0]['25']=url;
 widget['3']=name;
 widget['4']=`Weather 15 map host test ${name}. Fixed Ashdod example snapshot; map time and marker do not update. Other native data and all tabs preserved. Keep Weather 15 for daily use.`;
 const restored=structuredClone(widget);
 restored['3']=original['3'];restored['4']=original['4'];
 variable(restored)['3']['66'][0]['25']=variable(original)['3']['66'][0]['25'];
 assert(isDeepStrictEqual(restored,original),'Unexpected non-map difference');
 const bytes=Buffer.from(JSON.stringify(widget));
 const aad=Buffer.from(`map-host-ab-15:${name}:v1`),iv=randomBytes(12);
 const cipher=createCipheriv('aes-256-gcm',key,iv);cipher.setAAD(aad);
 const encrypted=Buffer.concat([cipher.update(gzipSync(bytes,{level:9})),cipher.final(),cipher.getAuthTag()]);
 const envelope={v:1,name,iv:iv.toString('base64url'),data:encrypted.toString('base64url'),bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')};
 const dec=createDecipheriv('aes-256-gcm',key,iv);dec.setAAD(aad);dec.setAuthTag(encrypted.subarray(-16));
 assert(gunzipSync(Buffer.concat([dec.update(encrypted.subarray(0,-16)),dec.final()])).equals(bytes),'Envelope roundtrip failed');
 fs.writeFileSync(`work/private/Map_Host_${name}.json`,bytes,{mode:0o600});
 fs.writeFileSync(`tools/map-host-ab-15-${name}.enc.json`,JSON.stringify(envelope)+'\n');
 output.push({name,bytes:bytes.length,sha256:envelope.sha256,layers:walk(widget['1']).length});
}
assert(fs.readFileSync('tools/widgy-health-premium-1.enc.json').equals(originals),'Daily copy changed');
fs.writeFileSync('work/private/map-host-ab-15-link.txt',`${origin}/tools/map-host-ab-15.html#key=${key.toString('base64url')}\n`,{mode:0o600});
console.log(JSON.stringify({copies:output,baselinePreserved:true,onlyChanges:['name','description','map_request URL']}));
